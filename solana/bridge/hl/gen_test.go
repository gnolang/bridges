const (
	gnoAddr        = "g1leu8d2vsplhehcfkjg50mwgdpxdkt8tztu95wr"
	solTestMailbox = "75HBBLae3ddeneJVrZeyrDfv6vb7SMC3aCpBucSXS5aR" // solanatestnet's mailbox: the hook its checkpoints name
)

// testAddress is gno's testutils.TestAddress: the name padded with '_' to twenty bytes, as a g1… address.
func testAddress(name string) string {
	b := []byte("____________________")
	copy(b, name)
	data, _ := bech32.ConvertBits(b, 8, 5, true)
	s, _ := bech32.Encode("g", data)
	return s
}

func mustB32(a string) [32]byte {
	b, err := GnoAddressToBytes32(a)
	if err != nil {
		panic(err)
	}
	return b
}

// vector is one message from Solana testnet to a gno test chain, with metadata signed by the listed validators.
type vector struct {
	name   string
	msg    Message
	signed []int
}

func (v vector) gno() string {
	raw := v.msg.Bytes()
	c := Checkpoint{Hook: MustKey32(solTestMailbox), Root: rep(0x11), Index: v.msg.Nonce}
	var sigs []EdSignature
	for _, i := range v.signed {
		sigs = append(sigs, EdSignature{uint8(i), SignEd25519(testEdKey(i), c, raw)})
	}
	return fmt.Sprintf("\t%sMsg  = %q\n\t%sMeta = %q\n", v.name, hx(raw), v.name, hx(GnoMetadata(c, sigs)))
}

func gnoFile(pkg string, vs []vector) string {
	var b strings.Builder
	b.WriteString("package " + pkg + "\n\n")
	b.WriteString("// Generated by bridge/hl (HL_GEN=<repo root> go test -run TestGenGnoVectors ./hl/); do not edit. Messages from Solana\n")
	b.WriteString("// testnet to a gno test chain, each with the checkpoint (solanatestnet's mailbox as the hook, root 0x11…, index = the\n")
	b.WriteString("// nonce) signed by test validators: ed25519 seeds sha256(\"hyperlane gno test validator <i>\").\n")
	b.WriteString("const (\n")
	var keys []string
	for i := 0; i < 3; i++ {
		keys = append(keys, hx(testEdKey(i).Public().(ed25519.PublicKey)))
	}
	fmt.Fprintf(&b, "\ttestValidators = %q\n\n", strings.Join(keys, ","))
	for _, v := range vs {
		b.WriteString(v.gno())
	}
	b.WriteString(")\n")
	return b.String()
}

func TestGenGnoVectors(t *testing.T) {
	root := os.Getenv("HL_GEN")
	if root == "" {
		t.Skip("HL_GEN=<repo root> writes the gno realms' vectors_test.gno")
	}
	body := []byte("hello, gno")
	rcpt := mustB32(testAddress("hlm-recipient"))
	mailbox := []vector{
		{"inHello", Message{3, 7, DomainSolanaTestnet, rep(0x5e), DomainGnoTest, rcpt, body}, []int{0, 2}},
		{"inMainnet", Message{3, 8, DomainSolanaTestnet, rep(0x5e), DomainGnoMainnet, rcpt, body}, []int{0, 1}},
		{"inOneSig", Message{3, 9, DomainSolanaTestnet, rep(0x5e), DomainGnoTest, rcpt, body}, []int{1}},
		{"inNoGroupA", Message{3, 10, DomainSolanaTestnet, rep(0x5e), DomainGnoTest, rcpt, body}, []int{1, 2}},
	}
	route := sha256.Sum256([]byte("hlbubble test route"))
	self := mustB32(GnoPackageAddress("gno.land/r/" + gnoAddr + "/hlbubble"))
	alice, bob := mustB32(testAddress("hlb-alice")), mustB32(testAddress("hlb-bob"))
	dirtyBob := bob
	for i := 0; i < 12; i++ {
		dirtyBob[i] = 0xff
	}
	const one = 1_000_000
	route2 := rep(0x66)
	// BUBBLE: the fee is 100 BUBBLE, so amounts under it are swept
	bubble := []vector{
		{"backAlice300", Message{3, 0, DomainSolanaTestnet, route, DomainGnoTest, self, TokenMessage(alice, 300*one, nil)}, []int{0, 1}},
		{"strangerRoute", Message{3, 1, DomainSolanaTestnet, route2, DomainGnoTest, self, TokenMessage(alice, 150*one, nil)}, []int{0, 1}},
		{"dirtyBob250", Message{3, 2, DomainSolanaTestnet, route, DomainGnoTest, self, TokenMessage(dirtyBob, 250*one, nil)}, []int{1, 2}},
		{"backAlice500", Message{3, 3, DomainSolanaTestnet, route, DomainGnoTest, self, TokenMessage(alice, 500*one, []byte("memo"))}, []int{0, 2}},
		{"backCarol50", Message{3, 4, DomainSolanaTestnet, route, DomainGnoTest, self, TokenMessage(mustB32(testAddress("hlb-carol")), 50*one, nil)}, []int{0, 1}},
	}
	// GNOT: the fee is 5 GNOT; the route realm's own address is the recipient the messages name
	groute := sha256.Sum256([]byte("hlgnot test route"))
	groute2 := sha256.Sum256([]byte("hlgnot test route 2"))
	gself := mustB32(GnoPackageAddress("gno.land/r/" + gnoAddr + "/hlgnot"))
	fees := mustB32(GnoPackageAddress("gno.land/r/" + gnoAddr + "/hlfees"))
	galice, gbob, gcarol, gdave := mustB32(testAddress("hlg-alice")), mustB32(testAddress("hlg-bob")), mustB32(testAddress("hlg-carol")), mustB32(testAddress("hlg-dave"))
	gnotv := []vector{
		{"inAlice100", Message{3, 0, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(galice, 100*one, nil)}, []int{0, 1}},
		{"inBob3", Message{3, 1, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(gbob, 3*one, nil)}, []int{1, 2}},
		{"inFees50", Message{3, 2, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(fees, 50*one, nil)}, []int{0, 2}},
		{"inAlice30000", Message{3, 3, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(galice, 30_000*one, nil)}, []int{0, 1}},
		{"strangerRoute", Message{3, 4, DomainSolanaTestnet, route2, DomainGnoTest, gself, TokenMessage(galice, 20*one, nil)}, []int{0, 1}},
		{"inCarol1000", Message{3, 5, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(gcarol, 1_000*one, nil)}, []int{0, 1}},
		{"inDave1000", Message{3, 6, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(gdave, 1_000*one, nil)}, []int{1, 2}},
		{"newRouteAlice7", Message{3, 7, DomainSolanaTestnet, groute2, DomainGnoTest, gself, TokenMessage(galice, 7*one, nil)}, []int{0, 1}},
		{"oldRouteAlice8", Message{3, 8, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(galice, 8*one, nil)}, []int{0, 2}},
		{"oldRouteAlice9", Message{3, 9, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(galice, 9*one, nil)}, []int{1, 2}},
		{"inBob60", Message{3, 10, DomainSolanaTestnet, groute, DomainGnoTest, gself, TokenMessage(gbob, 60*one, nil)}, []int{0, 1}},
		// the router addressing another realm of the bridge (AQ1): a successor takes its predecessor's messages once
		// the last page of a migration is in; a route that succeeded none refuses it before the mailbox is asked
		{"inOtherRealm60", Message{3, 11, DomainSolanaTestnet, groute, DomainGnoTest, mustB32(GnoPackageAddress("gno.land/r/" + gnoAddr + "/hlbubble")), TokenMessage(gbob, 60*one, nil)}, []int{0, 1}},
	}
	write := func(dir, pkg string, vs []vector, extra string) {
		p := filepath.Join(root, "realm", dir, "vectors_test.gno")
		src := gnoFile(pkg, vs)
		if extra != "" {
			src = strings.Replace(src, "\ttestValidators", extra+"\ttestValidators", 1)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", p)
	}
	write("hlmailbox", "hlmailbox", mailbox, "")
	write("hlverifier", "hlverifier", mailbox, "")
	write("hlbubble", "hlbubble", bubble, fmt.Sprintf("\ttestRoute = %q // sha256(\"hlbubble test route\"), base58\n", Base58(route[:])))
	write("hlgnot", "hlgnot", gnotv, fmt.Sprintf("\ttestRoute = %q // sha256(\"hlgnot test route\"), base58: the compiled launch router\n\ttestRoute2 = %q // sha256(\"hlgnot test route 2\"), base58\n", Base58(groute[:]), Base58(groute2[:])))
}
